import React from 'react';
import { KpiCard } from './KpiCard';
import { SkeletonCard } from '../common/LoadingSpinner';
import { formatCurrencyINR, formatNumber, formatPercent } from '../../utils/formatters';

export function KpiGrid({ summary, isLoading, onNavigateTab }) {
  if (isLoading && !summary) {
    return (
      <div className="kpi-grid">
        {Array.from({ length: 8 }).map((_, i) => (
          <SkeletonCard key={i} />
        ))}
      </div>
    );
  }

  const revenue = formatCurrencyINR(summary?.totalRevenue ?? 0);
  const grossProfit = formatCurrencyINR(summary?.grossProfit ?? 0);
  const grossMargin = formatPercent(summary?.grossMargin ?? 0);
  const sales = formatNumber(summary?.validSalesCount ?? 0);
  const units = formatNumber(summary?.unitsSold ?? 0);
  const activeProducts = formatNumber(summary?.activeProductCount ?? 0);
  const lowStock = formatNumber(summary?.lowStockProductCount ?? 0);
  const outOfStock = formatNumber(summary?.outOfStockProductCount ?? 0);
  const aov = formatCurrencyINR(summary?.averageOrderValue ?? 0);

  const isLowStockZero = (summary?.lowStockProductCount ?? 0) === 0;
  const isOutOfStockZero = (summary?.outOfStockProductCount ?? 0) === 0;

  return (
    <div className="kpi-grid">
      <KpiCard
        title="Sales Revenue"
        value={revenue}
        subtitle="Money earned from sales"
        icon="💰"
        variant="success"
        onClick={() => onNavigateTab && onNavigateTab('sales')}
        actionLabel="View sales ledger &rarr;"
        tooltip="Gross money collected from completed customer sales orders"
      />
      <KpiCard
        title="Retained Gross Profit"
        value={grossProfit}
        subtitle={`Profit after wholesale cost (${grossMargin})`}
        icon="📈"
        variant="purple"
        badge={`${grossMargin} Margin`}
        onClick={() => onNavigateTab && onNavigateTab('reports')}
        actionLabel="View profit statement &rarr;"
        tooltip="Net money retained by the business after deducting wholesale supplier item purchase costs"
      />
      <KpiCard
        title="Orders Completed"
        value={sales}
        subtitle="Number of valid sales"
        icon="🧾"
        variant="primary"
        onClick={() => onNavigateTab && onNavigateTab('sales')}
        actionLabel="Inspect order receipts &rarr;"
        tooltip="Total number of distinct, non-duplicate customer receipts"
      />
      <KpiCard
        title="Items Sold"
        value={units}
        subtitle="Total units sold"
        icon="📦"
        variant="info"
        onClick={() => onNavigateTab && onNavigateTab('products')}
        actionLabel="See top-selling items &rarr;"
        tooltip="Total quantity of individual merchandise items purchased"
      />
      <KpiCard
        title="Average Sale Size"
        value={aov}
        subtitle="Average amount per checkout"
        icon="📊"
        variant="primary"
        onClick={() => onNavigateTab && onNavigateTab('sales')}
        actionLabel="Analyze checkout sizes &rarr;"
        tooltip="Average revenue generated by each customer checkout (Total Revenue / Orders)"
      />
      <KpiCard
        title="Products In Catalogue"
        value={activeProducts}
        subtitle="Active listed SKUs"
        icon="🏷️"
        variant="primary"
        onClick={() => onNavigateTab && onNavigateTab('inventory', 'ALL')}
        actionLabel="Browse warehouse &rarr;"
        tooltip="Number of product items currently active in catalogue"
      />
      <KpiCard
        title="Items Running Low"
        value={lowStock}
        subtitle="At or near reorder threshold"
        icon="⚠️"
        variant={isLowStockZero ? 'success' : 'warning'}
        badge={isLowStockZero ? 'Healthy Stock' : 'Needs Restock'}
        onClick={() => onNavigateTab && onNavigateTab('inventory', 'LOW')}
        actionLabel={isLowStockZero ? 'Check warehouse &rarr;' : 'Review low stock &rarr;'}
        tooltip="Products currently at or below minimum threshold quantity"
      />
      <KpiCard
        title="Out of Stock"
        value={outOfStock}
        subtitle="Zero units on shelf"
        icon="🚨"
        variant={isOutOfStockZero ? 'success' : 'danger'}
        badge={isOutOfStockZero ? 'Fully Stocked' : 'Immediate Action'}
        onClick={() => onNavigateTab && onNavigateTab('inventory', 'OUT_OF_STOCK')}
        actionLabel={isOutOfStockZero ? 'Warehouse safe &rarr;' : 'Order units now &rarr;'}
        tooltip="Items completely exhausted (0 units on shelf) causing lost customer sales"
      />
    </div>
  );
}
