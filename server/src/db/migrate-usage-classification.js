const path = require('path');
require('dotenv').config({ path: path.resolve(__dirname, '../../.env') });
require('dotenv').config();
const { query } = require('./pool');

/**
 * Migration script to separate actual provider usage from internal engine metrics
 * and safely classify historical records in PostgreSQL.
 */
async function migrateUsageClassification() {
  console.log('[Migration] Starting AI Usage Classification Migration...');

  // 1. Add new columns to ai_usage_log if not already present
  await query(`
    ALTER TABLE ai_usage_log
      ADD COLUMN IF NOT EXISTS execution_type VARCHAR(50) DEFAULT 'provider_api' NOT NULL,
      ADD COLUMN IF NOT EXISTS provider_request_id VARCHAR(100),
      ADD COLUMN IF NOT EXISTS is_provider_verified BOOLEAN DEFAULT FALSE NOT NULL,
      ADD COLUMN IF NOT EXISTS internal_tokens_est INTEGER DEFAULT 0;

    CREATE INDEX IF NOT EXISTS idx_ai_usage_exec_type ON ai_usage_log (execution_type);
    CREATE INDEX IF NOT EXISTS idx_ai_usage_is_provider_verified ON ai_usage_log (is_provider_verified);
    CREATE INDEX IF NOT EXISTS idx_ai_usage_provider_req_id ON ai_usage_log (provider_request_id);
  `);
  console.log('✅ Added columns and indexes to ai_usage_log.');

  // 2. Classify rows 1-8: These were failed API attempts that returned 401 authentication_error
  const resAuth = await query(`
    UPDATE ai_usage_log
    SET
      execution_type = 'provider_api',
      status = 'auth_error',
      is_provider_verified = FALSE,
      input_tokens = 0,
      output_tokens = 0,
      total_tokens = 0,
      cache_read_tokens = 0,
      cache_write_tokens = 0,
      estimated_cost_usd = 0.000000,
      error_message = COALESCE(error_message, '401 authentication_error: invalid x-api-key (credentials rejected by Anthropic)'),
      metadata = jsonb_set(COALESCE(metadata, '{}'::jsonb), '{classification}', '"provider_auth_failure"')
    WHERE id <= 8;
  `);
  console.log(`✅ Classified ${resAuth.rowCount} historical failed provider requests (status='auth_error', tokens=0, cost=0).`);

  // 3. Classify rows 9 and above that were generated by internal fallback logic
  const resFallback = await query(`
    UPDATE ai_usage_log
    SET
      execution_type = 'internal_engine',
      status = 'fallback_completed',
      model = 'StockWise Retail BI Engine (Internal)',
      is_provider_verified = FALSE,
      internal_tokens_est = CASE WHEN internal_tokens_est > 0 THEN internal_tokens_est ELSE total_tokens END,
      input_tokens = 0,
      output_tokens = 0,
      total_tokens = 0,
      cache_read_tokens = 0,
      cache_write_tokens = 0,
      estimated_cost_usd = 0.000000,
      metadata = jsonb_set(COALESCE(metadata, '{}'::jsonb), '{classification}', '"internal_engine_fallback"')
    WHERE id >= 9 AND (is_provider_verified = FALSE OR provider_request_id IS NULL);
  `);
  console.log(`✅ Classified ${resFallback.rowCount} internal engine fallback records (execution_type='internal_engine', status='fallback_completed', provider_tokens=0, provider_cost=0).`);

  console.log('✅ AI Usage Classification Migration completed successfully.');
  return { ok: true, authRows: resAuth.rowCount, fallbackRows: resFallback.rowCount };
}

if (require.main === module) {
  migrateUsageClassification()
    .then((res) => {
      console.log('Migration Result:', res);
      process.exit(0);
    })
    .catch((err) => {
      console.error('❌ Migration failed:', err);
      process.exit(1);
    });
}

module.exports = { migrateUsageClassification };
